/**
 * 3/4 俯视相机作弊用的两个数字，所有把世界点放到屏幕上的代码都共用它们。
 * 移植自 overlord 的 Rendering.Projection。
 */
export const Projection = {
  /** 地面平面被相机压扁的比例 —— 相当于相机俯角的正弦。 */
  groundSquash: 0.55,

  /**
   * 一个物体的高度有多少能在投影后活下来 —— 实际上就是相机的俯角。
   *
   * 等于 1 时相机和人平视，全身沿着屏幕竖直展开：头在肩之上、肩在胯之上、两只脚平铺在
   * 下面 —— 那是一个贴着俯视地面的侧视图。调低它相机就往下压，人开始"望远镜式"收缩：
   * 头落到肩上，躯干盖住大腿，脚几乎消失在人自己底下。正是这种重叠让俯视的人读起来是
   * 有体积的，而不是一张纸片。
   *
   * 故意不等于 groundSquash（正交相机会要求相等）：完全对齐要么把地面压成一条带子，
   * 要么把每个人立成一块立牌。这一对不相等的数是标准作弊，取值靠眼睛定。
   */
  heightSquash: 0.68,
};
